    fn cursor_hooks_use_the_cli_schema() {
        let home = tempfile::tempdir().unwrap();
        let r = registration(home.path());
        let path = home.path().join(".cursor/hooks.json");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, r#"{"hooks":{"stop":[{"command":"mine"}]}}"#).unwrap();
        assert_eq!(r.set_enabled("cursor", true), Ok(Enrollment::Enabled));
        let value = read(path.clone());
        assert_eq!(value["version"], 1);
        assert_eq!(value["hooks"]["stop"][0]["command"], "mine");
        assert_eq!(value["hooks"]["preToolUse"][0]["matcher"], CURSOR_MATCHER);
        assert!(value["hooks"]["sessionEnd"][0].get("matcher").is_none());
        assert_eq!(
            r.set_enabled("cursor", false),
            Ok(Enrollment::NotConfigured)
        );
        assert_eq!(
            read(path.clone()),
            json!({ "version": 1, "hooks": { "stop": [{ "command": "mine" }] } })
        );
        std::fs::write(&path, r#"{"version":2}"#).unwrap();
        assert_eq!(r.inspect("cursor"), Enrollment::NeedsRepair);
        assert_eq!(
            r.set_enabled("cursor", true),
            Err("AGENT_ACTIVITY_CURSOR_CONFIG_UNSUPPORTED_VERSION".into())
        );
    }
