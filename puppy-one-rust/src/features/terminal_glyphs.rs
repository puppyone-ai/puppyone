//! xterm's custom glyphs (`customGlyphs: true` in the product terminal):
//! box drawing, block elements, shade patterns and Powerline symbols are
//! drawn across the whole cell from the product's own definitions
//! (`assets/terminal-glyphs.json`, imported by
//! `tools/import-xterm-glyphs.mjs`), so TUI frames join across the 1.24
//! line height and prompts need no Powerline font.
use gpui::{Bounds, ContentMask, PathBuilder, Pixels, Rgba, Window, fill, point, px, size};
use serde::Deserialize;
use std::{collections::HashMap, sync::OnceLock};

/// `a + b·e + c·t` for xterm's stroke parameters `e` and `t`.
type Linear = [f32; 3];

#[derive(Deserialize)]
struct Stroke {
    /// Device pixels per CSS pixel of line width (1 light, 3 heavy).
    weight: f32,
    path: Vec<(String, Vec<Linear>)>,
}

#[derive(Deserialize)]
struct Powerline {
    /// 1 strokes the outline; anything else fills it.
    #[serde(rename = "type")]
    kind: u8,
    left: f32,
    right: f32,
    path: Vec<(String, Vec<f32>)>,
}

#[derive(Deserialize)]
struct Definitions {
    /// Eighths of the cell: `[x, y, w, h]`.
    blocks: HashMap<String, Vec<[f32; 4]>>,
    patterns: HashMap<String, Vec<Vec<u8>>>,
    boxes: HashMap<String, Vec<Stroke>>,
    powerline: HashMap<String, Powerline>,
}

fn definitions() -> &'static Definitions {
    static DEFINITIONS: OnceLock<Definitions> = OnceLock::new();
    DEFINITIONS.get_or_init(|| {
        serde_json::from_str(include_str!("../../assets/terminal-glyphs.json"))
            .expect("assets/terminal-glyphs.json is generated by tools/import-xterm-glyphs.mjs")
    })
}

/// Whether the cell text is drawn here rather than by the font.
pub fn is_custom(text: &str) -> bool {
    let d = definitions();
    d.blocks.contains_key(text)
        || d.patterns.contains_key(text)
        || d.boxes.contains_key(text)
        || d.powerline.contains_key(text)
}

/// One instruction with its points already in window coordinates.
enum Step {
    Move(gpui::Point<Pixels>),
    Line(gpui::Point<Pixels>),
    Curve([gpui::Point<Pixels>; 3]),
}

fn steps<T>(path: &[(String, Vec<T>)], mut map: impl FnMut(&T, bool) -> Pixels) -> Vec<Step> {
    path.iter()
        .filter_map(|(command, numbers)| {
            let points: Vec<gpui::Point<Pixels>> = numbers
                .chunks_exact(2)
                .map(|xy| point(map(&xy[0], true), map(&xy[1], false)))
                .collect();
            match (command.as_str(), points.as_slice()) {
                ("M", [p, ..]) => Some(Step::Move(*p)),
                ("L", [p, ..]) => Some(Step::Line(*p)),
                ("C", [a, b, to, ..]) => Some(Step::Curve([*a, *b, *to])),
                _ => None,
            }
        })
        .collect()
}

fn build(steps: &[Step], mut builder: PathBuilder, close: bool) -> Option<gpui::Path<Pixels>> {
    for step in steps {
        match step {
            Step::Move(p) => builder.move_to(*p),
            Step::Line(p) => builder.line_to(*p),
            Step::Curve([a, b, to]) => builder.cubic_bezier_to(*to, *a, *b),
        }
    }
    if close {
        builder.close();
    }
    builder.build().ok()
}

/// Draw `text` over `cell` (the whole cell, line height included) in
/// `color`. `font_size` is the terminal's CSS size; `scale` the window's
/// device pixels per pixel. Returns whether `text` was a custom glyph.
pub fn paint(
    window: &mut Window,
    text: &str,
    cell: Bounds<Pixels>,
    font_size: f32,
    color: Rgba,
) -> bool {
    let d = definitions();
    let scale = window.scale_factor();
    let (x0, y0) = (f32::from(cell.origin.x), f32::from(cell.origin.y));
    let (w, h) = (f32::from(cell.size.width), f32::from(cell.size.height));
    if let Some(rects) = d.blocks.get(text) {
        for [x, y, rw, rh] in rects {
            window.paint_quad(fill(
                Bounds::new(
                    point(px(x0 + x * w / 8.), px(y0 + y * h / 8.)),
                    size(px(rw * w / 8.), px(rh * h / 8.)),
                ),
                color,
            ));
        }
        return true;
    }
    if let Some(tile) = d.patterns.get(text) {
        // The device-pixel tile, at its coverage.
        let cells = tile.iter().map(Vec::len).sum::<usize>().max(1);
        let on = tile.iter().flatten().filter(|v| **v != 0).count();
        window.paint_quad(fill(
            cell,
            Rgba {
                a: color.a * on as f32 / cells as f32,
                ..color
            },
        ));
        return true;
    }
    if let Some(strokes) = d.boxes.get(text) {
        // xterm: `e` = .15 and `t` = .15 / cellHeight * cellWidth; points
        // snap to device-pixel centres inside the cell.
        let (dw, dh) = (w * scale, h * scale);
        let (e, t) = (0.15, 0.15 / dh * dw);
        for stroke in strokes {
            let steps = steps(&stroke.path, |[a, b, c], horizontal| {
                let extent = if horizontal { dw } else { dh };
                let mut v = (a + b * e + c * t) * extent;
                if v != 0. {
                    v = ((v + 0.5).round() - 0.5).clamp(0., extent);
                }
                px(if horizontal { x0 } else { y0 } + v / scale)
            });
            if let Some(path) = build(&steps, PathBuilder::stroke(px(stroke.weight)), false) {
                window.paint_path(path, color);
            }
        }
        return true;
    }
    if let Some(glyph) = d.powerline.get(text) {
        // Strokes and paddings scale with the font (`fontSize / 12`).
        let unit = font_size / 12.;
        let (left, right) = (glyph.left * unit / 2., glyph.right * unit / 2.);
        let steps = steps(&glyph.path, |v, horizontal| {
            px(if horizontal {
                x0 + left + v * (w - left - right)
            } else {
                y0 + v * h
            })
        });
        let stroked = glyph.kind == 1;
        let builder = if stroked {
            PathBuilder::stroke(px(unit))
        } else {
            PathBuilder::fill()
        };
        if let Some(path) = build(&steps, builder, !stroked) {
            window.with_content_mask(Some(ContentMask { bounds: cell }), |window| {
                window.paint_path(path, color)
            });
        }
        return true;
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;
    use core::prelude::v1::test;

    #[test]
    fn the_product_definitions_cover_frames_blocks_shades_and_powerline() {
        for glyph in [
            "─", "│", "╭", "╯", "═", "┼", "█", "▀", "░", "▓", "\u{e0b0}", "\u{e0bb}",
        ] {
            assert!(is_custom(glyph), "{glyph:?}");
        }
        for text in ["a", " ", "中", "→"] {
            assert!(!is_custom(text), "{text:?}");
        }
        // Rounded corners bend with the cell's aspect (`t`).
        let corner = &definitions().boxes["╭"][0];
        assert_eq!(corner.weight, 1.);
        assert!(
            corner
                .path
                .iter()
                .flat_map(|(_, n)| n)
                .any(|[_, _, c]| *c != 0.)
        );
    }
}
