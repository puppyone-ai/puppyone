#!/usr/bin/env python3
"""Regenerate src/assets.rs from assets/icons, agents, brand and integrations.
Run after tools/import-icons.mjs; --check fails when the table is stale."""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parents[1]
icons = sorted(p.stem for p in (root / 'assets/icons').glob('*.svg'))
agents = sorted(p.name for p in (root / 'assets/agents').iterdir() if p.suffix in ('.svg', '.png', '.txt'))
brand = sorted(p.name for p in (root / 'assets/brand').glob('*.svg'))
integrations = sorted(p.name for p in (root / 'assets/integrations').glob('*.svg'))
entries = '\n'.join([f'    "icons" / "{i}.svg",' for i in icons] + [f'    "agents" / "{a}",' for a in agents]
                    + [f'    "brand" / "{b}",' for b in brand]
                    + [f'    "integrations" / "{i}",' for i in integrations])
source = f'''//! Embedded product assets, generated by `tools/generate-assets-rs.py`.
//! Icon names mirror `tools/import-icons.mjs`; file-type glyphs are produced on
//! demand from `assets/file-icons.json`; any other path falls back to GPUI Kit.
use gpui::{{AssetSource, SharedString}};
use std::borrow::Cow;
macro_rules! embedded {{
    ($($dir:literal / $name:literal),* $(,)?) => {{
        fn embedded(path: &str) -> Option<&'static [u8]> {{
            match path {{
                $(concat!($dir, "/", $name) => Some(include_bytes!(concat!("../assets/", $dir, "/", $name)).as_slice()),)*
                _ => None,
            }}
        }}
        /// Every embedded path, for tests that guard references against missing files.
        #[cfg(test)]
        pub const EMBEDDED: &[&str] = &[$(concat!($dir, "/", $name)),*];
    }};
}}
embedded! {{
{entries}
}}
pub struct Assets;
impl AssetSource for Assets {{
    fn load(&self, path: &str) -> anyhow::Result<Option<Cow<'static, [u8]>>> {{
        if path.starts_with("file-icons/") {{
            return Ok(crate::file_kind::glyph_svg(path).map(Cow::Owned));
        }}
        if let Some(svg) = stroke_variant(path) {{
            return Ok(Some(Cow::Owned(svg)));
        }}
        match embedded(path) {{
            Some(bytes) => Ok(Some(Cow::Borrowed(bytes))),
            None => gpui_kit::assets::Assets.load(path),
        }}
    }}
    fn list(&self, path: &str) -> anyhow::Result<Vec<SharedString>> {{
        gpui_kit::assets::Assets.list(path)
    }}
}}
/// `icons/<name>@<stroke>.svg`: the embedded Lucide icon redrawn at the
/// product call site's `strokeWidth` (icons are imported at 1.8).
fn stroke_variant(path: &str) -> Option<Vec<u8>> {{
    let (name, stroke) = path
        .strip_prefix("icons/")?
        .strip_suffix(".svg")?
        .split_once('@')?;
    let stroke: f32 = stroke
        .parse()
        .ok()
        .filter(|s: &f32| s.is_finite() && *s > 0.)?;
    let base = std::str::from_utf8(embedded(&format!("icons/{{name}}.svg"))?).ok()?;
    let (before, after) = base.split_once("stroke-width=\\"")?;
    let (_, rest) = after.split_once('"')?;
    Some(format!("{{before}}stroke-width=\\"{{stroke}}\\"{{rest}}").into_bytes())
}}
/// True when `icons/<name>.svg` resolves from the product or Kit assets.
#[cfg(test)]
pub fn has_icon(name: &str) -> bool {{
    let path = format!("icons/{{name}}.svg");
    embedded(&path).is_some() || matches!(gpui_kit::assets::Assets.load(&path), Ok(Some(_)))
}}
#[cfg(test)]
mod tests {{
    use super::*;
    /// Every literal icon name passed to the shared icon helpers must resolve.
    #[test]
    fn referenced_icons_exist() {{
        let mut missing = vec![];
        let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut stack = vec![src];
        while let Some(dir) = stack.pop() {{
            for entry in std::fs::read_dir(dir).unwrap().flatten() {{
                let path = entry.path();
                if path.is_dir() {{
                    stack.push(path);
                    continue;
                }}
                if path.extension().is_none_or(|e| e != "rs") {{
                    continue;
                }}
                let text = std::fs::read_to_string(&path).unwrap();
                for pattern in ["icon(\\"", "icon_sized(\\"", "menu_icon(\\"", "icon_stroke(\\""] {{
                    for (index, _) in text.match_indices(pattern) {{
                        let rest = &text[index + pattern.len()..];
                        let Some(end) = rest.find('"') else {{ continue }};
                        let name = &rest[..end];
                        let icon_like = !name.is_empty()
                            && name
                                .bytes()
                                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
                        if icon_like && !has_icon(name) {{
                            missing.push(format!("{{}}: {{name}}", path.display()));
                        }}
                    }}
                }}
            }}
        }}
        assert!(missing.is_empty(), "missing icons: {{missing:#?}}");
        assert!(EMBEDDED.contains(&"icons/history.svg"));
        let variant = String::from_utf8(stroke_variant("icons/x@1.9.svg").unwrap()).unwrap();
        assert!(variant.contains("stroke-width=\\"1.9\\""));
        assert!(stroke_variant("icons/x@nan.svg").is_none());
    }}
}}
'''
target = root / 'src/assets.rs'
if '--check' in sys.argv:
    if target.read_text() != source:
        raise SystemExit('Stale asset table: run python3 tools/generate-assets-rs.py')
    print('Asset table verified')
else:
    target.write_text(source)
    print(f'Asset table: {len(icons)} icons, {len(agents)} agent assets')
